/**
 * B2-A: единственное место, где серверный компонент читает текущее время.
 *
 * `Date.now()` прямо в теле серверного компонента линтер считает side-effect'ом
 * рендера (react-hooks/purity), хотя для SSR это норма. Вызов вынесен в модуль,
 * чтобы правило не отключать: время читается явно и в одном месте.
 */
export function serverNow(): number {
  return Date.now();
}
