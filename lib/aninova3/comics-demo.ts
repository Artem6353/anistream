export function findDemoComic(slug: string) {
  return DEMO_COMICS.find((c) => c.slug === slug) ?? null;
}

export function demoChapters(comic: DemoComic) {
  /* Даты убывают от фиксированной точки: последняя глава — 2026-11-01,
     каждая предыдущая на 21 день раньше. Без «случайных» будущих дат. */
  const base = Date.UTC(2026, 10, 1);
  return Array.from({ length: Math.min(12, comic.chapters) }, (_, i) => {
    const number = comic.chapters - i;
    const date = new Date(base - i * 21 * 86400000).toISOString().slice(0, 10);
    return { number, title: `Глава ${number}`, date };
  });
}

